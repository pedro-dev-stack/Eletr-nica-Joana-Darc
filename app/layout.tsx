import type { Metadata, Viewport } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";
import { LenisProvider } from "@/Components/LenisProvider";
import { SeasonalOverlay } from "@/Components/Seasonaloverlay";
import { getCurrentSeason, SEASON_THEME_COLOR } from "@/lib/Seasons";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

/**
 * A temporada depende da data. Sem isto, uma página estática ficaria
 * "congelada" na temporada do dia do build. Com revalidate, o Next refaz
 * a página a cada hora e o tema vira sozinho na virada do mês.
 */
export const revalidate = 3600;

export const metadata: Metadata = {
  title: "Eletronica Joana Dark",
  description: "Generated by create next app",
  icons: {
    icon: "/Logo.jpeg",
  },
};

/** theme-color da barra do navegador acompanha a temporada. */
export function generateViewport(): Viewport {
  return { themeColor: SEASON_THEME_COLOR[getCurrentSeason()] };
}

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const season = getCurrentSeason();

  return (
    <html lang="pt-BR" data-season={season}>
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        <LenisProvider>{children}</LenisProvider>
        <SeasonalOverlay season={season} />
      </body>
    </html>
  );
}